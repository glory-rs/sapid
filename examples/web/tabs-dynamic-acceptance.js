async (hostPage) => {
  const context = await hostPage.context().browser().newContext({viewport:{width:1440,height:1100}});
  const reports=[], errors=[];
  const assert=(value,message)=>{if(!value)throw new Error(message);};
  const base=process.env.SAPID_TABS_BASE || 'http://127.0.0.1:8794';
  try {
    const page=await context.newPage();
    const turn=()=>page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    page.on('pageerror',error=>errors.push(error.message));
    page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
    for(const hue of ['blue','green'])for(const scheme of ['light','dark'])for(const hydrate of [false,true]) {
      const mode=`tabs-dynamic-${hue}-${scheme}-${hydrate?'hydrate':'csr'}`;
      await page.setViewportSize({width:1440,height:1100});
      await page.goto(`${base}/${hydrate?`tabs-dynamic-hydrate-${hue}-${scheme}.html`:`tabs-dynamic.html?theme=${hue}&scheme=${scheme}`}`);
      await page.waitForFunction(()=>window.ready===true);
      const root=page.locator('.controlled-dynamic-tabs'),local=page.locator('.local-dynamic-tabs');
      const control=name=>page.getByRole('button',{name,exact:true});
      let prefix='Section ';
      const tab=key=>root.getByRole('tab',{name:prefix+key,exact:true});
      const status=async()=>{
        const text=await page.locator('.dynamic-tabs-status').textContent();
        const value=text.match(/Proposals: (\d+); factories: (\d+); value: ([^;]*); order: (.*)/);
        assert(value,`${mode}: status shape ${text}`);
        return {proposals:+value[1],factories:+value[2],value:value[3],order:value[4]};
      };
      const selected=async key=>assert(await tab(key).getAttribute('aria-selected')==='true',`${mode}: ${key} not selected`);
      await selected('alpha');
      assert(await tab('beta').isDisabled(),`${mode}: disabled item`);
      assert(await root.locator('[role=tab][tabindex="0"]').count()===1,`${mode}: initial single tab stop`);
      await root.locator('.dynamic-tab-editor-alpha').fill('Retained α draft');await turn();
      await tab('alpha').evaluate(element=>window.savedDynamicTabs=[element,document.getElementById(element.getAttribute('aria-controls')),document.querySelector('.dynamic-tab-editor-alpha'),element.querySelector('.dynamic-tab-caption')]);
      const cdp=await context.newCDPSession(page),ax=await cdp.send('Accessibility.getFullAXTree');
      const axTab=ax.nodes.find(node=>!node.ignored&&node.role?.value==='tab'&&node.name?.value==='Section alpha'&&node.properties?.some(property=>property.name==='selected'&&property.value.value===true));
      assert(axTab&&ax.nodes.some(node=>!node.ignored&&node.role?.value==='tablist'&&node.name?.value==='Document sections')&&ax.nodes.some(node=>!node.ignored&&node.role?.value==='tabpanel'&&node.name?.value==='Section alpha'),`${mode}: real Chrome Tab/TabList/TabPanel relations`);
      await cdp.detach();
      await tab('gamma').click();await turn();
      await selected('alpha');
      assert((await status()).proposals>0&&(await status()).order==='typed generic',`${mode}: controlled refusal or typed/generic order`);
      await control('Toggle proposal acceptance').click();await turn();
      await tab('gamma').click();await turn();await selected('gamma');
      const accepted=await status();
      assert(accepted.value==='gamma',`${mode}: controlled acceptance`);
      await control('Rotate members').click();await turn();
      assert(JSON.stringify(await root.getByRole('tab').evaluateAll(elements=>elements.map(element=>element.getAttribute('aria-label'))))===JSON.stringify(['Section gamma','Section alpha','Section beta']),`${mode}: current DOM order`);
      assert(await tab('alpha').evaluate(element=>element===window.savedDynamicTabs[0]&&document.getElementById(element.getAttribute('aria-controls'))===window.savedDynamicTabs[1]&&document.querySelector('.dynamic-tab-editor-alpha')===window.savedDynamicTabs[2]),`${mode}: surviving identity replaced`);
      assert((await status()).factories===3,`${mode}: reorder reran configuration factory`);
      await tab('gamma').press('ArrowLeft');await turn();await selected('alpha');
      assert(await tab('alpha').evaluate(element=>element===document.activeElement),`${mode}: RTL logical next focus`);
      assert(await root.locator('.dynamic-tab-editor-alpha').inputValue()==='Retained α draft',`${mode}: KeepMounted lost draft`);
      await tab('alpha').press('ArrowLeft');await turn();await selected('gamma');
      assert(await tab('gamma').evaluate(element=>element===document.activeElement),`${mode}: disabled skip/wrap`);
      await control('Toggle language').click();await turn();prefix='章节 ';
      assert(await tab('alpha').evaluate(element=>element.querySelector('.dynamic-tab-caption')===window.savedDynamicTabs[3]&&element.querySelector('.dynamic-tab-caption').textContent==='章节 alpha'),`${mode}: locale update replaced text`);
      await control('Toggle beta enabled').click();await turn();
      await tab('alpha').focus();await turn();await tab('alpha').press('ArrowLeft');await turn();await selected('beta');
      await control('Toggle root enabled').click();await turn();
      assert(await root.locator('[role=tab]:disabled').count()===3&&await root.locator('[role=tab][tabindex="0"]').count()===0,`${mode}: root enabled AND/roving retirement`);
      const beforeSource=(await status()).proposals;
      await tab('gamma').evaluate(element=>element.click());await turn();
      await control('Select alpha from source').click();await turn();await selected('alpha');
      assert((await status()).proposals===beforeSource,`${mode}: disabled or source emitted proposal`);
      await control('Toggle root enabled').click();await turn();
      await control('Toggle proposal acceptance').click();await turn();
      await root.locator('.dynamic-tab-editor-alpha').focus();await turn();
      const beforeRemoval=(await status()).proposals;
      await control('Remove alpha').evaluate(element=>element.click());await turn();await turn();
      assert(await tab('gamma').evaluate(element=>element===document.activeElement),`${mode}: focused member retirement did not hand off`);
      assert(await root.locator('[role=tab][aria-selected=true]').count()===0&&(await status()).value==='alpha'&&(await status()).proposals===beforeRemoval,`${mode}: automatic membership handoff overwrote controlled absent intent`);
      assert(await page.evaluate(()=>!window.savedDynamicTabs[0].isConnected&&!window.savedDynamicTabs[2].isConnected),`${mode}: removed Owner retained DOM`);
      await control('Add alpha').click();await turn();await selected('alpha');
      assert(await tab('alpha').evaluate(element=>element!==window.savedDynamicTabs[0]),`${mode}: reinsert revived retired identity`);
      assert((await status()).factories===4&&await root.locator('.dynamic-tab-editor-alpha').inputValue()==='Initial draft',`${mode}: reinsert reused retired factory/editor`);
      const beforeUser=(await status()).proposals;
      await tab('beta').focus();await turn();
      assert((await status()).proposals===beforeUser+1,`${mode}: restoration marker swallowed later real focus`);
      await selected('alpha');
      const localAlpha=local.locator('.local-dynamic-tab-editor-alpha');
      assert(await localAlpha.count()===0,`${mode}: local repair should select current first member gamma`);
      const localGamma=local.getByRole('tab',{name:'Local gamma',exact:true});
      await localGamma.focus();await turn();
      await localGamma.press('ArrowDown');await turn();
      assert(await local.getByRole('tab',{name:'Local beta',exact:true}).evaluate(element=>element===document.activeElement),`${mode}: vertical manual focus ignored current order`);
      assert(await localGamma.getAttribute('aria-selected')==='true',`${mode}: manual focus auto-selected`);
      await local.getByRole('tab',{name:'Local beta',exact:true}).press('Space');await turn();
      assert(await local.getByRole('tab',{name:'Local beta',exact:true}).getAttribute('aria-selected')==='true'&&await local.locator('.local-dynamic-tab-editor-gamma').count()===0,`${mode}: manual activation/Unmount`);
      const beforeEmpty=(await status()).proposals;
      await control('Empty members').click();await turn();
      assert(await root.getByRole('tab').count()===0&&await local.getByRole('tab').count()===0,`${mode}: empty set retained registrations`);
      await control('Restore members').click();await turn();await selected('alpha');
      assert((await status()).factories===7&&(await status()).proposals===beforeEmpty,`${mode}: empty/restore history or proposal`);
      await page.setViewportSize({width:390,height:900});await turn();
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`${mode}: mobile overflow`);
      if(hydrate)await page.screenshot({path:`D:/BuildCache/sapid/${mode}.png`,fullPage:true});
      reports.push({mode,realAX:{role:axTab.role.value,name:axTab.name.value},identity:true,controlledAbsent:true,rtl:true,manual:true,mobile:true});
      await page.evaluate(()=>window.demo.unmount_display());await turn();
      assert(await page.locator('#app').textContent()==='',`${mode}: Owner cleanup`);
    }
    await page.setViewportSize({width:1440,height:1100});
    await page.goto(`${base}/tabs-dynamic.html`);await page.waitForFunction(()=>window.ready===true);
    const root=page.locator('.controlled-dynamic-tabs');
    await page.getByRole('button',{name:'Toggle beta enabled',exact:true}).click();await turn();
    await root.locator('.dynamic-tab-editor-alpha').focus();await turn();
    await root.getByRole('tab',{name:'Section beta',exact:true}).evaluate(element=>{window.refusedDynamicTab=element;element.style.display='none';});
    await page.getByRole('button',{name:'Remove alpha',exact:true}).evaluate(element=>element.click());await turn();await turn();
    assert((await page.locator('.dynamic-tabs-status').textContent()).startsWith('Proposals: 0;'),`refused focus: membership handoff proposed selection`);
    await page.evaluate(()=>window.refusedDynamicTab.style.removeProperty('display'));
    await root.getByRole('tab',{name:'Section beta',exact:true}).focus();await turn();
    assert((await page.locator('.dynamic-tabs-status').textContent()).startsWith('Proposals: 1;'),`refused focus: expired marker swallowed later actual user focus`);
    reports.push({mode:'tabs-dynamic-refused-host-focus',confirmation:true,subsequentUserFocus:true});
    await page.evaluate(()=>window.demo.unmount_display());await turn();
    assert(errors.length===0,errors.join('\n'));
    return {reports,errors};
  } finally {await context.close();}
}

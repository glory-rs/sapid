"""Generate the explicit finite-contract ledger and docs gallery; no network/build."""
import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
inventory = json.loads((ROOT / "docs/widget-inventory.json").read_text(encoding="utf-8"))
ledger = json.loads((ROOT / "docs/capability-matrix.json").read_text(encoding="utf-8"))
tasks = {task["id"]: task for task in inventory["tasks"]}
records = {record["id"]: record for record in ledger["tasks"]}
if len(tasks) != len(inventory["tasks"]) or len(records) != len(ledger["tasks"]) or set(records) != set(tasks):
    raise SystemExit("capability ledger must cover every inventory ID exactly once")
axes = ["model", "ssr", "web", "native", "accesskit"]
states = {"tested", "model-only", "rejected", "pending"}
for identity, record in records.items():
    for axis in axes:
        cell = record[axis]
        if cell["state"] not in states or not cell["notes"].strip():
            raise SystemExit(f"invalid {identity}/{axis}")
        if cell["state"] != "pending" and not cell["evidence"]:
            raise SystemExit(f"missing explicit evidence reference: {identity}/{axis}")
        if any(reference != f"inventory:{identity}" for reference in cell["evidence"]):
            raise SystemExit(f"unknown evidence reference: {identity}/{axis}")
    for page in record["pages"]:
        if not page.replace("-", "").isalnum() or not (ROOT / f"examples/web/{page}.html").is_file():
            raise SystemExit(f"invalid fixture page: {identity}/{page}")

ssr = (ROOT / "examples/web/src/bin/ssr.rs").read_text(encoding="utf-8")
rows = []
markdown = [
    "# Per-item adapter capability ledger", "",
    "Generated by `python scripts/capability-gallery.py` from the canonical inventory",
    "and the explicitly reviewed `docs/capability-matrix.json`. Completion status never",
    "infers adapter support. `tested` covers the stated finite contract; `model-only`",
    "does not claim a host driver; `rejected` is an explicit typed host boundary;",
    "`pending` makes no acceptance claim. Variant restrictions are part of each cell.", "",
    "AccessKit projection, protocol IME and browser emulation do not establish OS IME,",
    "screen-reader speech, physical touch devices or an untested AT client. Native",
    "Layer/popup, radio, file, clipboard, precision-pointer and style limitations remain",
    "explicit even when another variant of the same family is available.", "",
    "| ID / component | Inventory | Model | SSR | Web | Native | AccessKit |", "|---|---|---|---|---|---|---|",
]
for identity, task in tasks.items():
    record = records[identity]
    cells = []
    for axis in axes:
        cell = record[axis]
        notes = cell["notes"].replace("|", "\\|").replace("\n", " ")
        cells.append(f"**{cell['state']}**: {notes}")
    name = task["name"].replace("|", "\\|")
    markdown.append(f"| [{identity} {name}](#evidence-{identity.lower()}) | {task['status']} | " + " | ".join(cells) + " |")
    pages = []
    for page in record["pages"]:
        stem = "hydrate" if page == "index" else f"{page}-hydrate"
        pages.append({"name": page, "hydrate": f'"{stem}"' in ssr})
    rows.append({"id":identity,"phase":task["phase"],"name":task["name"],"status":task["status"],"work":task["work"],"pages":pages,"capabilities":{axis:record[axis] for axis in axes},"evidence":task.get("evidence", {})})
markdown += ["", "## Evidence references", ""]
for identity, task in tasks.items():
    markdown += [f"### Evidence {identity}", "", task["work"], ""]
    for key, values in task.get("evidence", {}).items():
        markdown.append(f"{key.capitalize()}:")
        markdown.append("")
        markdown.extend(f"- `{value}`" for value in values)
        markdown.append("")
    if not task.get("evidence"):
        markdown += ["No canonical acceptance evidence recorded yet.", ""]

encoded = json.dumps(rows, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c").replace("&", "\\u0026")
table = []
for row in rows:
    cells = "".join(f'<td class="state-{row["capabilities"][axis]["state"]}">{html.escape(row["capabilities"][axis]["state"])}</td>' for axis in axes)
    table.append(f'<tr data-id="{row["id"]}"><th scope="row"><button type="button" data-select="{row["id"]}">{html.escape(row["name"])}</button><small>{row["id"]}</small></th><td>{html.escape(row["status"])}</td>{cells}</tr>')
gallery = '''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="icon" href="data:,"><title>Sapid component gallery</title><link rel="stylesheet" href="gallery.css"></head><body>
<header><h1>Sapid component gallery</h1><p>Finite contracts, live examples and explicit adapter boundaries.</p><div class="toolbar"><label>Search <input id="gallery-search" type="search" placeholder="Component or ID"></label><label>Phase <select id="gallery-phase"><option value="">All phases</option></select></label><label>Completion <select id="gallery-status"><option value="">All states</option><option>done</option><option>partial</option><option>planned</option></select></label><label>Palette <select id="gallery-hue"><option>blue</option><option>green</option></select></label><label>Scheme <select id="gallery-scheme"><option>light</option><option>dark</option></select></label></div><p id="gallery-count" role="status"></p></header>
<main><section aria-label="Component capabilities" class="ledger"><table><thead><tr><th scope="col">Component</th><th scope="col">Completion</th><th scope="col">Model</th><th scope="col">SSR</th><th scope="col">Web</th><th scope="col">Native</th><th scope="col">AccessKit</th></tr></thead><tbody>''' + "".join(table) + '''</tbody></table></section>
<section class="detail" aria-label="Selected component"><h2 id="gallery-title">Select a component</h2><p id="gallery-work"></p><dl id="gallery-capabilities"></dl><div class="toolbar"><label>Example <select id="gallery-example"></select></label><label>Render <select id="gallery-render"><option value="csr">CSR</option><option value="hydrate">SSR adoption</option></select></label><a id="gallery-open" target="_blank" rel="noopener noreferrer">Open example</a></div><p id="gallery-preview-note"></p><iframe id="gallery-preview" title="Interactive component example" loading="eager" aria-busy="false" hidden></iframe><details><summary>Canonical evidence</summary><div id="gallery-evidence"></div></details></section></main>
<footer><p>Tested means the documented finite contract. Model-only does not advertise an input driver. Rejected means explicit typed refusal. Pending means no acceptance claim.</p><p>AX projection and emulated input do not establish screen-reader announcements, physical touch, OS IME or an untested AT client.</p></footer>
<script id="gallery-data" type="application/json">''' + encoded + '''</script><script src="gallery.js"></script></body></html>'''
outputs = {ROOT / "docs/component-capabilities.md": "\n".join(markdown) + "\n", ROOT / "examples/web/gallery.html": gallery + "\n"}
for path, content in outputs.items():
    if args.check:
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"stale generated output: {path}")
    else:
        path.write_text(content, encoding="utf-8")
print(f"{len(rows)} explicit capability rows; gallery and evidence {'checked' if args.check else 'generated'}")
